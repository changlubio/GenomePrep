from __future__ import annotations

import io
from unittest.mock import MagicMock, patch
import pytest

from genomeprep.qc import filter_by_badalleles, get_snp_reference, MIN_CLUSTER_COVERAGE, MIN_COUNT_SNP
from genomeprep._types import SNPRecord


def _snp(**kwargs: str) -> SNPRecord:
    base: SNPRecord = {"rsid": "rs1", "chro": "1", "pos": "100", "call": "AA", "ref": "A", "gav": ""}
    base.update(kwargs)  # type: ignore[typeddict-item]
    return base


class TestFilterByBadalleles:
    def test_marks_bad_snps(self):
        snps = [_snp(chro="1", pos="100"), _snp(chro="1", pos="200")]
        bad: set[str] = {"1:100"}
        result = filter_by_badalleles(snps, bad)
        assert result[0]["ba"] is True
        assert result[1]["ba"] is False

    def test_empty_bad_set_marks_all_good(self):
        snps = [_snp(), _snp(pos="200")]
        result = filter_by_badalleles(snps, set())
        assert all(not s["ba"] for s in result)

    def test_returns_same_length(self):
        snps = [_snp() for _ in range(5)]
        result = filter_by_badalleles(snps, {"1:100"})
        assert len(result) == 5


class TestGetSnpReference:
    def test_returns_ref_base(self):
        mock_faidx = MagicMock()
        mock_faidx["1"][99].seq = "A"
        result = get_snp_reference("1:100", mock_faidx)
        assert result == "A"

    def test_returns_none_on_key_error(self):
        mock_faidx = MagicMock()
        mock_faidx.__getitem__.side_effect = KeyError("1")
        result = get_snp_reference("1:100", mock_faidx)
        assert result is None

    def test_returns_none_on_bad_loci_format(self):
        mock_faidx = MagicMock()
        result = get_snp_reference("bad_loci", mock_faidx)
        assert result is None


class TestDtcReadRecords:
    def test_rejects_when_fewer_than_min_count_snp(self):
        from genomeprep.parser import DTCparser
        from genomeprep.qc import dtc_read_records
        mock_faidx = MagicMock()
        mock_faidx.__getitem__.return_value.__getitem__.return_value.seq = "A"
        content = "# generated by 23andMe\nrs1\t1\t100\tAA\n"
        parser = DTCparser(io.StringIO(content))
        reject, reject_type, store_snps, *_ = dtc_read_records(
            parser, set(), mock_faidx, {}, {}
        )
        assert reject
        assert reject_type == "invalid"
        assert store_snps == []

    def test_counts_duplicates(self):
        from genomeprep.parser import DTCparser
        from genomeprep.qc import dtc_read_records
        mock_faidx = MagicMock()
        mock_faidx.__getitem__.return_value.__getitem__.return_value.seq = "A"
        # Two lines with same position = one duplicate
        content = "# generated by 23andMe\nrs1\t1\t100\tAA\nrs2\t1\t100\tAA\n"
        parser = DTCparser(io.StringIO(content))
        _, _, _, count_snps, duplicate_snps, *_ = dtc_read_records(
            parser, set(), mock_faidx, {}, {}
        )
        assert count_snps == 2
        assert len(duplicate_snps) == 1


