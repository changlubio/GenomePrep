import io
import os

from genomeprep.parser import DTCparser, DTCrecord

FIXTURES = os.path.join(os.path.dirname(__file__), "fixtures")


def make_handle(content: str) -> io.StringIO:
    return io.StringIO(content)


class TestDTCparserHeaderDetection:
    def test_detects_23andme(self):
        handle = make_handle("# This file was generated by 23andMe at:\nrs1\t1\t100\tAA\n")
        p = DTCparser(handle)
        assert p.company == "23andme"
        assert not p.reject

    def test_detects_ancestrydna(self):
        handle = make_handle("#AncestryDNA raw data download\nrs1\t1\t100\tA\tA\n")
        p = DTCparser(handle)
        assert p.company == "ancestrydna"
        assert not p.reject

    def test_detects_ftdna(self):
        handle = make_handle('RSID,CHROMOSOME,POSITION,RESULT\n"rs1","1","100","AA"\n')
        p = DTCparser(handle)
        assert p.company == "ftdna"
        assert not p.reject

    def test_detects_myheritage(self):
        handle = make_handle("##MyHeritage DNA raw data download\nrs1,1,100,AA\n")
        p = DTCparser(handle)
        assert p.company == "myheritage"
        assert not p.reject

    def test_falls_back_to_all_on_unknown_header(self):
        handle = make_handle("unknown header line\nrs1\t1\t100\tAA\n")
        p = DTCparser(handle)
        assert p.company == "all"

    def test_rejects_grch36(self):
        handle = make_handle(
            "# This file was generated by 23andMe at:\n# build 36\nrs1\t1\t100\tAA\n"
        )
        p = DTCparser(handle)
        assert p.reject
        assert p.reject_type == "grch36"
        assert p.build == "GRCh36"

    def test_rejects_grch38(self):
        handle = make_handle(
            "# This file was generated by 23andMe at:\n# build 38\nrs1\t1\t100\tAA\n"
        )
        p = DTCparser(handle)
        assert p.reject
        assert p.reject_type == "grch38"
        assert p.build == "GRCh38"

    def test_rejects_empty_file(self):
        handle = make_handle("")
        p = DTCparser(handle)
        assert p.reject
        assert p.reject_type == "invalid"


