class TestDTCrecord:
    def test_23andme_valid(self):
        r = DTCrecord("rs4477212\t1\t82154\tAA\n", "23andme")
        assert r.rsid == "rs4477212"
        assert r.chro == "1"
        assert r.pos == "82154"
        assert r.genotype == "AA"
        assert not r.badsnp
        assert r.goodrsid
        assert r.loci == "1:82154"

    def test_ancestrydna_chromosome_x_mapping(self):
        r = DTCrecord("rs1\t23\t100\tA\tA\n", "ancestrydna")
        assert r.chro == "X"
        assert r.genotype == "AA"

    def test_ancestrydna_chromosome_y_mapping(self):
        r = DTCrecord("rs1\t24\t100\tA\tA\n", "ancestrydna")
        assert r.chro == "Y"

    def test_ancestrydna_chromosome_mt_mapping(self):
        r = DTCrecord("rs1\t26\t100\tA\tA\n", "ancestrydna")
        assert r.chro == "MT"

    def test_ftdna_valid(self):
        r = DTCrecord('"rs1","1","100","AA"\n', "ftdna")
        assert r.rsid == "rs1"
        assert r.genotype == "AA"
        assert not r.badsnp

    def test_badsnp_invalid_chromosome(self):
        r = DTCrecord("rs1\t99\t100\tAA\n", "23andme")
        assert r.badsnp

    def test_badsnp_invalid_genotype_chars(self):
        r = DTCrecord("rs1\t1\t100\tZZ\n", "23andme")
        assert r.badsnp

    def test_badsnp_empty_genotype(self):
        r = DTCrecord("rs1\t1\t100\t\n", "23andme")
        assert r.badsnp

    def test_decodeme_flips_minus_strand(self):
        r = DTCrecord("rs1,var,1,100,-,AC\n", "decodeme")
        assert r.genotype == "TG"

    def test_goodrsid_false_for_non_rs(self):
        r = DTCrecord("i12345\t1\t100\tAA\n", "23andme")
        assert not r.goodrsid
